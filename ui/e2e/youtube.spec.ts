import { expect, test } from './fixtures'
import { deleteLibraryTrack, login, navigate, openUploadDialog } from './helpers'
import { writeFile } from 'node:fs/promises'
import { join } from 'node:path'

// Only the external YouTube downloader is substituted; conversion, storage, and playback are real.
test.use({ youtubeFixture: true })

test('GM imports a YouTube link into a table and plays the audio', async ({ page, app }) => {
  await login(page)
  await openUploadDialog(page)
  await page.getByRole('tab', { name: 'YouTube link', exact: true }).click()
  const submit = page.getByRole('button', { name: 'Import', exact: true })
  await expect(submit).toBeDisabled()
  await page.getByLabel('YouTube URL', { exact: true }).fill('https://youtu.be/aaaaaaaaaaa?list=ignored')
  await expect(page.getByLabel('Track Name', { exact: true })).toHaveValue('YouTube Forest')
  await expect(page.getByLabel('Duration', { exact: true })).toHaveValue('0:00:12')
  await expect(page.getByLabel('Audio size', { exact: true })).toHaveValue('1.0 MiB')
  await expect(submit).toBeDisabled()
  await page.getByRole('combobox', { name: 'Track Type', exact: true }).press('ArrowDown')
  await page.getByRole('option', { name: 'Music', exact: true }).click()
  await submit.click()
  await expect(page.getByRole('status').filter({ hasText: 'Track added' })).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.reload()
  const tile = page.locator('.file-tile').filter({ hasText: 'YouTube Forest' })
  await expect(tile).toBeVisible()
  await expect(tile).toHaveAttribute('aria-disabled', 'true')
  await expect(tile.getByRole('progressbar', { name: 'Processing YouTube Forest' })).toBeVisible()
  await tile.hover()
  await expect(page.getByRole('tooltip').filter({ hasText: 'Track is still processing' })).toBeVisible()
  await expect(tile).toBeDisabled()
  await tile.focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('video')).toHaveCount(0)
  await writeFile(join(app.scratch, 'import-release'), '')
  await expect(tile).toHaveAttribute('aria-disabled', 'false')
  await tile.click()
  await expect.poll(() => page.locator('video').first().evaluate(
    (media: HTMLVideoElement) => !media.paused && media.currentTime > 0,
  )).toBe(true)
  await navigate(page, 'Library')
  await expect(page.getByRole('row').filter({ hasText: 'YouTube Forest' })).toBeVisible()
  await deleteLibraryTrack(page, 'YouTube Forest', 1)
})

test('GM corrects an unavailable YouTube link in the library import dialog', async ({ page, app }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await login(page)
  await navigate(page, 'Library')
  await openUploadDialog(page)
  await page.getByRole('tab', { name: 'YouTube link', exact: true }).click()
  await page.getByLabel('YouTube URL', { exact: true }).fill('https://youtu.be/bbbbbbbbbbb')
  await expect(page.getByText('Could not retrieve video metadata.', { exact: false })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Import', exact: true })).toBeDisabled()
  await page.getByLabel('YouTube URL', { exact: true }).fill('https://youtu.be/aaaaaaaaaaa')
  await expect(page.getByLabel('Track Name', { exact: true })).toHaveValue('YouTube Forest')
  await page.getByLabel('Track Name', { exact: true }).fill('Imported Music')
  await page.getByRole('combobox', { name: 'Track Type', exact: true }).press('ArrowDown')
  await page.getByRole('option', { name: 'Music', exact: true }).click()
  await page.getByRole('button', { name: 'Import', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const row = page.getByRole('row').filter({ hasText: 'Imported Music' })
  await expect(row).toHaveAttribute('aria-busy', 'true')
  await expect(row.getByRole('button', { name: 'Preview Imported Music' })).toHaveCount(0)
  await writeFile(join(app.scratch, 'import-release'), '')
  await expect(row).toHaveAttribute('aria-busy', 'false')
  await page.reload()
  await deleteLibraryTrack(page, 'Imported Music', 0)
})

test('GM sees YouTube limit errors on the URL before importing', async ({ page }) => {
  await login(page)
  await openUploadDialog(page)
  await page.getByRole('tab', { name: 'YouTube link', exact: true }).click()
  const url = page.getByLabel('YouTube URL', { exact: true })
  await url.fill('https://youtu.be/ggggggggggg')
  await expect(page.getByText('Video exceeds the 3-hour limit', { exact: true })).toBeVisible()
  await expect(page.locator('.v-input').filter({ has: url })).toHaveClass(/v-input--error/)
  await expect(page.getByRole('button', { name: 'Import', exact: true })).toBeDisabled()
  await url.fill('https://youtu.be/hhhhhhhhhhh')
  await expect(page.getByText('Audio exceeds the 200 MiB limit', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Import', exact: true })).toBeDisabled()
})
