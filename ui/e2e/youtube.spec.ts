test('GM inspects a failed YouTube import and removes it from the table', async ({ page, app }) => {
  await login(page)
  await openUploadDialog(page)
  await page.getByRole('tab', { name: 'YouTube link', exact: true }).click()
  await page.getByLabel('YouTube URL', { exact: true }).fill('https://youtu.be/lllllllllll')
  await expect(page.getByLabel('Track Name', { exact: true })).toHaveValue('YouTube Forest')
  await page.getByRole('combobox', { name: 'Track Type', exact: true }).press('ArrowDown')
  await page.getByRole('option', { name: 'Music', exact: true }).click()
  await page.getByRole('button', { name: 'Import', exact: true }).click()
  const tile = page.getByRole('group', { name: 'YouTube Forest', exact: true })
  await expect(tile).toHaveAttribute('aria-busy', 'true')
  const processingHeight = (await tile.boundingBox())?.height
  await writeFile(join(app.scratch, 'import-release'), '')
  const warning = tile.getByRole('button', { name: 'View processing failure for YouTube Forest', exact: true })
  await expect(warning).toBeVisible()
  await expect(tile.getByRole('progressbar')).toHaveCount(0)
  expect((await tile.boundingBox())?.height).toBe(processingHeight)
  await expect(page.locator('video')).toHaveCount(0)
  await tile.click()
  const dialog = page.getByRole('dialog', { name: 'Track processing failed', exact: true })
  const diagnostics = dialog.getByLabel('Processing diagnostics', { exact: true })
  await expect(diagnostics).toContainText("Command:\n'yt-dlp' '--ignore-config'")
  await expect(diagnostics).toContainText("'--match-filter' '!is_live & duration <= 10800'")
  await expect(diagnostics).toContainText("'--' 'https://www.youtube.com/watch?v=lllllllllll'")
  await expect(diagnostics).toContainText('[youtube] Download attempt 40')
  await expect(diagnostics).toContainText('ERROR: Sign in to confirm you are not a bot.')
  await expect(diagnostics).toContainText('<script>alert("untrusted output")</script>')
  await expect(diagnostics).toContainText('Error:\nexit status 1')
  await expect(diagnostics.locator('script')).toHaveCount(0)
  await expect(diagnostics).toHaveCSS('overflow-y', 'auto')
  expect(await diagnostics.evaluate(el => el.scrollHeight > el.clientHeight)).toBe(true)
  await diagnostics.focus()
  await diagnostics.press('Control+End')
  await expect.poll(() => diagnostics.evaluate(el => el.scrollTop)).toBeGreaterThan(0)
  const fullDiagnostics = await diagnostics.innerText()
  await dialog.getByRole('button', { name: 'Close track controls', exact: true }).click()
  await page.reload()
  await tile.press('Enter')
  await expect(diagnostics).toHaveText(fullDiagnostics)
  await dialog.getByRole('button', { name: 'Close track controls', exact: true }).click()
  await page.setViewportSize({ width: 375, height: 812 })
  await warning.click()
  await expect(diagnostics).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await expect(dialog.getByRole('textbox')).toHaveCount(0)
  await expect(dialog.getByRole('button')).toHaveCount(2)
  const remove = dialog.getByRole('button', { name: 'Delete track', exact: true })
  await expect(remove).toHaveClass(/v-btn--variant-flat/)
  await remove.click()
  const confirmation = page.getByRole('dialog', { name: 'Delete track?', exact: true })
  await expect(confirmation).toContainText('remove it from 1 table')
  await confirmation.getByRole('button', { name: 'Confirm delete track', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(tile).toHaveCount(0)
  await page.reload()
  await expect(tile).toHaveCount(0)
  await navigate(page, 'Library')
  await expect(page.getByRole('row').filter({ hasText: 'YouTube Forest' })).toHaveCount(0)
})

