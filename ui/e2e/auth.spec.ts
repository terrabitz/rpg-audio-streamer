test('error toasts can be dismissed and expire automatically', async ({ page }, testInfo) => {
  await page.goto('/login')
  await page.getByLabel('Username').fill('e2e-gm')
  await page.getByLabel('Password', { exact: true }).fill('wrong-password')
  await page.getByRole('button', { name: 'Login', exact: true }).click()
  const error = page.getByRole('alert').filter({ hasText: 'Invalid credentials' })
  await expect(error).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('error-toast.png') })
  await page.getByRole('button', { name: 'Dismiss error', exact: true }).click()
  await expect(error).not.toBeVisible()
  await page.getByRole('button', { name: 'Login', exact: true }).click()
  await expect(error).toBeVisible()
  await expect(error).not.toBeVisible({ timeout: 7000 })
  await expect(page.getByRole('textbox', { name: 'Username', exact: true })).toBeVisible()
})
